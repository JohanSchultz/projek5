-- Creates app_private.birthdays if missing, aligns columns, and defines public.pu_birthdays_import.

CREATE SCHEMA IF NOT EXISTS app_private;

CREATE TABLE IF NOT EXISTS app_private.birthdays (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  tag boolean,
  noemnaam text,
  van text,
  ouderdom integer,
  verjaardag date,
  selfoon text
);

ALTER TABLE app_private.birthdays
  ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'app_private'
      AND table_name = 'birthdays'
      AND column_name = 'verjaardsdag'
  ) THEN
    ALTER TABLE app_private.birthdays RENAME COLUMN verjaardsdag TO verjaardag;
  END IF;
END $$;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'app_private'
      AND table_name = 'birthdays'
      AND column_name = 'verjaardag'
      AND data_type <> 'date'
  ) THEN
    ALTER TABLE app_private.birthdays
      ALTER COLUMN verjaardag TYPE date
      USING NULLIF(trim(verjaardag::text), '')::date;
  END IF;
END $$;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'app_private'
      AND table_name = 'birthdays'
      AND column_name = 'ouderdom'
      AND data_type <> 'integer'
  ) THEN
    ALTER TABLE app_private.birthdays
      ALTER COLUMN ouderdom TYPE integer
      USING round(ouderdom)::integer;
  END IF;
END $$;

CREATE OR REPLACE FUNCTION public.pu_birthdays_import(p_rows jsonb)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = app_private, public
AS $$
BEGIN
  TRUNCATE TABLE app_private.birthdays RESTART IDENTITY;

  IF p_rows IS NULL OR jsonb_typeof(p_rows) <> 'array' THEN
    RETURN;
  END IF;

  INSERT INTO app_private.birthdays (
    tag,
    noemnaam,
    van,
    ouderdom,
    verjaardag,
    selfoon
  )
  SELECT
    CASE
      WHEN lower(coalesce(r->>'tag', '')) IN ('true', '1', 'yes', 't', 'y') THEN true
      WHEN lower(coalesce(r->>'tag', '')) IN ('false', '0', 'no', 'f', 'n', '') THEN false
      ELSE NULL
    END,
    nullif(trim(r->>'noemnaam'), ''),
    nullif(trim(r->>'van'), ''),
    nullif(trim(r->>'ouderdom'), '')::integer,
    nullif(trim(coalesce(r->>'verjaardag', r->>'verjaardsdag')), '')::date,
    nullif(trim(r->>'selfoon'), '')
  FROM jsonb_array_elements(p_rows) AS r
  WHERE coalesce(trim(r->>'noemnaam'), '') <> ''
     OR coalesce(trim(r->>'van'), '') <> '';
END;
$$;

REVOKE ALL ON FUNCTION public.pu_birthdays_import(jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.pu_birthdays_import(jsonb) TO anon;
GRANT EXECUTE ON FUNCTION public.pu_birthdays_import(jsonb) TO authenticated;
GRANT EXECUTE ON FUNCTION public.pu_birthdays_import(jsonb) TO service_role;

NOTIFY pgrst, 'reload schema';